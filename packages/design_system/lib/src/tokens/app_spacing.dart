/// Espaciados. `s<n>` son los de Figma (`spacing/<n>`); `xs`…`xl` son nombres
/// cortos de los más usados.
abstract final class AppSpacing {
  static const double s0 = 0.0;
  static const double s50 = 2.0;
  static const double s100 = 4.0;
  static const double s150 = 6.0;
  static const double s200 = 8.0;
  static const double s300 = 12.0;
  static const double s400 = 16.0;
  static const double s500 = 20.0;
  static const double s600 = 24.0;
  static const double s800 = 32.0;
  static const double s1000 = 40.0;
  static const double s1200 = 48.0;
  static const double s1600 = 64.0;

  static const double xs = s100;
  static const double sm = s200;
  static const double md = s400;
  static const double lg = s600;
  static const double xl = s800;
}
